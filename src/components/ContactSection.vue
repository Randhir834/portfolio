<script>
import { onMounted, onUnmounted } from 'vue'
import ContactForm from './ContactForm.vue'
import { useAnimations } from '@/composables/useAnimations'

export default {
  name: 'ContactSection',
  components: {
    ContactForm
  },
  setup() {
    let observer = null
    const { fadeInUp, fadeInLeft, fadeInRight } = useAnimations()

    onMounted(() => {
      const section = document.querySelector('section#contact')
      if (section) {
        observer = new IntersectionObserver((entries) => {
          entries.forEach(entry => {
            if (entry.isIntersecting) {
              // Animate header
              fadeInUp('section#contact h2', 0)
              fadeInUp('section#contact .text-center p', 200)
              
              // Animate contact info cards
              const contactCards = document.querySelectorAll('section#contact .flex.items-start')
              contactCards.forEach((card, index) => {
                fadeInLeft(card, index * 150)
              })
              
              // Animate contact form
              fadeInRight('section#contact > div > div:last-child', 400)
              
              observer.unobserve(entry.target)
            }
          })
        }, { threshold: 0.1 })
        
        observer.observe(section)
      }
    })

    onUnmounted(() => {
      if (observer) {
        observer.disconnect()
      }
    })

    return {}
  }
}
</script>


